#!/usr/bin/env bash
# Workshop participant setup. Idempotent — safe to re-run.
# Tested on macOS with Homebrew python3.13.

set -e
cd "$(dirname "$0")/.."
ROOT="$(pwd)"

echo "▶ workshop_demo setup at $ROOT"
echo ""

# 1. Make scripts executable.
echo "→ chmod hook + demo scripts"
chmod +x day1_advanced/hooks/.claude/hooks/block-prod-writes.sh 2>/dev/null || true
chmod +x day2_adlc/headless/quick_demo.sh 2>/dev/null || true
chmod +x scripts/render-show.sh 2>/dev/null || true
chmod +x scripts/test_all.sh 2>/dev/null || true

# 2. Pick the best available python (mcp needs >= 3.10).
echo ""
echo "→ finding a python >= 3.10 for the MCP server"
PY=""
for cand in python3.13 python3.12 python3.11 python3.10 python3 python; do
  if command -v "$cand" >/dev/null 2>&1 && \
     "$cand" -c 'import sys; sys.exit(0 if sys.version_info >= (3,10) else 1)' 2>/dev/null; then
    PY="$(command -v "$cand")"
    echo "   ✓ found $PY ($("$PY" -V 2>&1))"
    break
  fi
done
if [ -z "$PY" ]; then
  echo "   ✗ no python >= 3.10 found. Install with: brew install python@3.13"
  echo "   (you can still run everything except the MCP demo)"
fi

# 3. Create venv + install mcp inside day1_advanced/mcp.
if [ -n "$PY" ]; then
  echo ""
  echo "→ creating day1_advanced/mcp/.venv with mcp installed"
  # Recreate the venv if it's missing OR broken (e.g. the repo directory
  # moved, which invalidates the shebang paths inside .venv/bin).
  if ! day1_advanced/mcp/.venv/bin/pip --version >/dev/null 2>&1 && \
     ! day1_advanced/mcp/.venv/Scripts/pip.exe --version >/dev/null 2>&1; then
    rm -rf day1_advanced/mcp/.venv
    "$PY" -m venv day1_advanced/mcp/.venv
  fi
  # Windows venvs use Scripts/, POSIX venvs use bin/ — support both.
  VENV_BIN="day1_advanced/mcp/.venv/bin"
  [ -d "$VENV_BIN" ] || VENV_BIN="day1_advanced/mcp/.venv/Scripts"
  "$VENV_BIN/python" -m pip install --quiet --upgrade pip
  "$VENV_BIN/python" -m pip install --quiet mcp
  echo "   ✓ mcp installed in day1_advanced/mcp/.venv"

  # 4. Patch the MCP settings.json to point at this venv.
  VENV_PY="$ROOT/$VENV_BIN/python"
  SERVER_PATH="$ROOT/day1_advanced/mcp/oncall_server.py"
  cat > day1_advanced/mcp/.claude/settings.json <<JSON
{
  "_comment": "Auto-generated by scripts/setup.sh — uses .venv python so mcp is importable.",
  "mcpServers": {
    "oncall": {
      "command": "$VENV_PY",
      "args": ["$SERVER_PATH"]
    }
  }
}
JSON
  echo "   ✓ patched day1_advanced/mcp/.claude/settings.json"
fi

# 5. Sanity-check binaries.
echo ""
echo "→ checking required tools:"
for cmd in claude jq git; do
  if command -v "$cmd" >/dev/null 2>&1; then
    printf "   ✓ %s\n" "$cmd"
  else
    printf "   ✗ %s — please install before the workshop\n" "$cmd"
  fi
done
if command -v bat >/dev/null 2>&1; then
  printf "   ✓ bat (nice-to-have)\n"
else
  printf "   - bat not installed (optional; cat works as a fallback)\n"
fi

# 6. Smoke-test claude.
echo ""
if [ -t 0 ]; then
  echo "→ claude doctor:"
  claude doctor 2>&1 | sed 's/^/   /' | head -10 || echo "   ! claude not authenticated"
else
  echo "→ skipping claude doctor (non-interactive shell) — run it yourself once"
fi

# 7. Seed sandbox_repo git history (so M6's /standup has something to summarise).
echo ""
if [ -d sandbox_repo ]; then
  if [ ! -d sandbox_repo/.git ]; then
    echo "→ seeding sandbox_repo with fake git history"
    (
      cd sandbox_repo
      git init -q -b main
      git config user.email "you@example.com"
      git config user.name "You"

      # Build a tiny credible history. Backdate so /standup has 'since main'
      # commits to summarise.
      GIT_AUTHOR_DATE="2026-05-06T10:00:00" GIT_COMMITTER_DATE="2026-05-06T10:00:00" \
        git add README.md package.json src/app.ts && \
        git commit -q -m "initial scaffold: express + prisma + vitest"

      GIT_AUTHOR_DATE="2026-05-07T11:30:00" GIT_COMMITTER_DATE="2026-05-07T11:30:00" \
        git add src/middleware/auth.ts tests/routes/users.test.ts && \
        git commit -q -m "auth: add TOKEN_CACHE middleware + first route test"

      GIT_AUTHOR_DATE="2026-05-07T16:45:00" GIT_COMMITTER_DATE="2026-05-07T16:45:00" \
        git add src/routes/users.ts && \
        git commit -q -m "routes: add GET /users/:id and DELETE /users/:id"

      # First branch divergence happens here — main is "stable".
      git branch main-stable

      GIT_AUTHOR_DATE="2026-05-08T09:15:00" GIT_COMMITTER_DATE="2026-05-08T09:15:00" \
        git add src/db/migrations/0042_add_soft_delete.sql && \
        git commit -q -m "WIP: migration 0042 soft-delete (TODO: rollback)"

      GIT_AUTHOR_DATE="2026-05-08T14:20:00" GIT_COMMITTER_DATE="2026-05-08T14:20:00" \
        git add tests/db/migration_0042.test.ts && \
        git commit -q -m "test: add rollback assertion for migration 0042"

      GIT_AUTHOR_DATE="2026-05-09T10:00:00" GIT_COMMITTER_DATE="2026-05-09T10:00:00" \
        git add CLAUDE.md .claude/settings.json && \
        git commit -q -m "docs: seed CLAUDE.md and .claude/settings.json (review pending)"

      # Now leave .git in a state where:
      #  - HEAD has the WIP migration + failing test commits since main-stable
      #  - working tree has no uncommitted changes
      #  - /standup will have 3 commits to summarise from the "since main-stable" diff
    ) && echo "   ✓ sandbox_repo seeded with 6 commits across 4 days"
  else
    echo "→ sandbox_repo/.git already exists; skipping seed"
  fi
fi

echo ""
echo "▶ setup done."
echo "  next: run 'bash scripts/test_all.sh' to verify every demo end-to-end."
